ALTER TABLE despesa
    ADD COLUMN criador_id BIGINT,
    ADD COLUMN cancelada_por_id BIGINT;

ALTER TABLE despesa
    ADD CONSTRAINT fk_despesa_criador FOREIGN KEY (criador_id) REFERENCES participacao (id),
    ADD CONSTRAINT fk_despesa_cancelada_por FOREIGN KEY (cancelada_por_id) REFERENCES participacao (id),
    ADD CONSTRAINT ck_despesa_cancelamento_completo CHECK (
        (data_cancelamento IS NULL AND cancelada_por_id IS NULL)
        OR (data_cancelamento IS NOT NULL AND cancelada_por_id IS NOT NULL)
    ) NOT VALID;

CREATE TABLE parcela_despesa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    despesa_id BIGINT NOT NULL,
    participacao_id BIGINT NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    incluida BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_parcela_despesa_uuid UNIQUE (uuid),
    CONSTRAINT uk_parcela_despesa_participacao UNIQUE (despesa_id, participacao_id),
    CONSTRAINT fk_parcela_despesa FOREIGN KEY (despesa_id) REFERENCES despesa (id),
    CONSTRAINT fk_parcela_participacao FOREIGN KEY (participacao_id) REFERENCES participacao (id),
    CONSTRAINT ck_parcela_valor_positivo CHECK (valor > 0)
);

CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    parcela_id BIGINT NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    data_pagamento DATE NOT NULL,
    data_registro TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    forma VARCHAR(30) NOT NULL,
    finalidade VARCHAR(30) NOT NULL,
    destinatario VARCHAR(255) NOT NULL,
    observacao VARCHAR(255),
    status VARCHAR(30) NOT NULL,
    confirmado_por_id BIGINT,
    data_confirmacao TIMESTAMP(6) WITHOUT TIME ZONE,
    cancelado_por_id BIGINT,
    data_cancelamento TIMESTAMP(6) WITHOUT TIME ZONE,
    motivo_cancelamento VARCHAR(255),
    CONSTRAINT uk_pagamento_uuid UNIQUE (uuid),
    CONSTRAINT fk_pagamento_parcela FOREIGN KEY (parcela_id) REFERENCES parcela_despesa (id),
    CONSTRAINT fk_pagamento_confirmado_por FOREIGN KEY (confirmado_por_id) REFERENCES participacao (id),
    CONSTRAINT fk_pagamento_cancelado_por FOREIGN KEY (cancelado_por_id) REFERENCES participacao (id),
    CONSTRAINT ck_pagamento_valor_positivo CHECK (valor > 0),
    CONSTRAINT ck_pagamento_status CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'CANCELADO')),
    CONSTRAINT ck_pagamento_forma CHECK (
        forma IN ('PIX', 'DINHEIRO', 'TRANSFERENCIA', 'CARTAO', 'OUTRO')),
    CONSTRAINT ck_pagamento_finalidade CHECK (finalidade IN ('CONTRIBUICAO', 'REEMBOLSO')),
    CONSTRAINT ck_pagamento_destinatario CHECK (btrim(destinatario) <> ''),
    CONSTRAINT ck_pagamento_finalizacao CHECK (
        (status = 'PENDENTE' AND confirmado_por_id IS NULL AND data_confirmacao IS NULL
            AND cancelado_por_id IS NULL AND data_cancelamento IS NULL AND motivo_cancelamento IS NULL)
        OR (status = 'CONFIRMADO' AND confirmado_por_id IS NOT NULL AND data_confirmacao IS NOT NULL
            AND cancelado_por_id IS NULL AND data_cancelamento IS NULL AND motivo_cancelamento IS NULL)
        OR (status = 'CANCELADO' AND confirmado_por_id IS NULL AND data_confirmacao IS NULL
            AND cancelado_por_id IS NOT NULL AND data_cancelamento IS NOT NULL
            AND btrim(motivo_cancelamento) <> '')
    )
);

CREATE INDEX ix_parcela_participacao ON parcela_despesa (participacao_id);
CREATE INDEX ix_pagamento_parcela_status ON pagamento (parcela_id, status);
CREATE INDEX ix_despesa_republica_referencia ON despesa (republica_id, data_referencia);
